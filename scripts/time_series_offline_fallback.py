@dataclass(frozen=True)
class OfflineFallbackOutcome:
    """Typed success or refusal; refusal means no canonical files published."""

    status: Literal["generated", "refused"]
    code: str
    reason: str
    provenance: dict[str, object] | None = None
    written_files: tuple[str, ...] = ()

    @property
    def generated(self) -> bool:
        return self.status == "generated"

    def as_dict(self) -> dict[str, object]:
        return {
            "status": self.status,
            "code": self.code,
            "reason": self.reason,
            "provenance": self.provenance,
            "written_files": list(self.written_files),
        }


class OfflineFallbackValidationError(ValueError):
    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code


@dataclass(frozen=True)
class _Quantity:
    role: str
    raw_value: int | float | None
    unit: str
    granularity: Decimal
    paper_value_status: str
    steps: int
    value_source: str
    paper_element_ids: tuple[str, ...]
    axis_paper_element_ids: tuple[str, ...]

    def provenance(self) -> dict[str, object]:
        return {
            "role": self.role,
            "raw_value": self.raw_value,
            "unit": self.unit,
            "granularity": _json_number(self.granularity),
            "paper_value_status": self.paper_value_status,
            "steps": self.steps,
            "value_source": self.value_source,
            "paper_element_ids": list(self.paper_element_ids),
            "axis_paper_element_ids": list(self.axis_paper_element_ids),
        }


@dataclass(frozen=True)
class _Plan:
    entity_count: int
    seed: int
    unit: str
    granularity: Decimal
    cadence_microseconds: int
    quantities: tuple[_Quantity, ...]
    family_fitting_prefix_steps: int
    usable_steps: int
    attempts: tuple[dict[str, object], ...]
    scheme: dict[str, object]
    family_contract: dict[str, object]

    @property
    def by_role(self) -> dict[str, _Quantity]:
        return {item.role: item for item in self.quantities}


def _canonical_json(value: object) -> str:
    try:
        return json.dumps(
            value, sort_keys=True, separators=(",", ":"), ensure_ascii=False,
            allow_nan=False,
        )
    except (TypeError, ValueError) as exc:
        raise OfflineFallbackValidationError(
            "offline_fallback_not_json", f"evidence is not canonical JSON: {exc}",
        ) from exc


def _digest(value: object) -> str:
    return hashlib.sha256(_canonical_json(value).encode("utf-8")).hexdigest()


def _json_number(value: Decimal) -> int | float:
    integral = value.to_integral_value()
    return int(integral) if value == integral else float(value)


def _object(value: object, root: str) -> Mapping[str, object]:
    if not isinstance(value, Mapping):
        raise OfflineFallbackValidationError(
            "offline_fallback_contract_shape", f"{root} must be an object",
        )
    return value


def _exact_keys(
    value: Mapping[str, object], expected: frozenset[str], root: str,
) -> None:
    keys = set(value)
    if keys != expected:
        raise OfflineFallbackValidationError(
            "offline_fallback_contract_shape",
            f"{root} has unsupported shape; missing={sorted(expected - keys)}, "
            f"unknown={sorted(keys - expected)}",
        )


def _positive_int(value: object, root: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        raise OfflineFallbackValidationError(
            "offline_fallback_positive_integer",
            f"{root} must be a positive integer, got {value!r}",
        )
    return value


def _decimal(value: object, root: str) -> Decimal:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise OfflineFallbackValidationError(
            "offline_fallback_protocol_quantity",
            f"{root} must be a raw numeric JSON value, got {value!r}",
        )
    try:
        result = Decimal(str(value))
    except (InvalidOperation, ValueError) as exc:
        raise OfflineFallbackValidationError(
            "offline_fallback_protocol_quantity", f"{root} is not numeric",
        ) from exc
    if not result.is_finite() or result <= 0:
        raise OfflineFallbackValidationError(
            "offline_fallback_protocol_quantity",
            f"{root} must be finite and positive, got {value!r}",
        )
    return result


def _ids(value: object, root: str) -> tuple[str, ...]:
    if not isinstance(value, Sequence) or isinstance(value, (str, bytes)):
        raise OfflineFallbackValidationError(
            "offline_fallback_protocol_evidence",
            f"{root} must be a list of string ids",
        )
    result: list[str] = []
    for item in value:
        if not isinstance(item, str) or not item or item != item.strip():
            raise OfflineFallbackValidationError(
                "offline_fallback_protocol_evidence",
                f"{root} must contain nonblank already-stripped string ids",
            )
        result.append(item)
    if not result or len(result) != len(set(result)):
        raise OfflineFallbackValidationError(
            "offline_fallback_protocol_evidence",
            f"{root} must be nonempty and unique",
        )
    return tuple(result)


def _column(value: object, root: str) -> dict[str, str]:
    item = _object(value, root)
    _exact_keys(item, _COLUMN_KEYS, root)
    normalized: dict[str, str] = {}
    for key in ("name", "dtype", "semantic_role"):
        field = item.get(key)
        if not isinstance(field, str) or not field or field != field.strip():
            raise OfflineFallbackValidationError(
                "offline_fallback_contract_shape",
                f"{root}.{key} must be a nonblank string",
            )
        normalized[key] = field
    return normalized


def _table(
    value: object, root: str, expected_columns: tuple[dict[str, str], ...],
    expected_key: tuple[str, ...],
) -> dict[str, object]:
    item = _object(value, root)
    _exact_keys(item, _TABLE_KEYS, root)
    raw_columns = item.get("columns")
    if not isinstance(raw_columns, list):
        raise OfflineFallbackValidationError(
            "offline_fallback_contract_shape", f"{root}.columns must be a list",
        )
    columns = [_column(value, f"{root}.columns[{index}]")
               for index, value in enumerate(raw_columns)]
    if columns != list(expected_columns):
        raise OfflineFallbackValidationError(
            "offline_fallback_table_schema",
            f"{root}.columns disagree with the closed {SCHEMA_ID} schema",
        )
    primary_key = item.get("primary_key")
    if not isinstance(primary_key, list) or tuple(primary_key) != expected_key:
        raise OfflineFallbackValidationError(
            "offline_fallback_table_schema",
            f"{root}.primary_key must be {list(expected_key)!r}",
        )
    return {"columns": columns, "primary_key": list(expected_key)}


def _family_contract(build_plan: object) -> dict[str, object]:
    resolved = _object(build_plan, "build_plan")
    contract = _object(
        resolved.get("offline_demo_data"), "build_plan.offline_demo_data",
    )
    _exact_keys(contract, _OFFLINE_KEYS, "build_plan.offline_demo_data")
    if contract.get("schema_id") != SCHEMA_ID:
        raise OfflineFallbackValidationError(
            "offline_fallback_schema_unsupported",
            f"only schema_id={SCHEMA_ID!r} is supported",
        )
    if contract.get("synthetic_feasible") is not True:
        raise OfflineFallbackValidationError(
            "offline_fallback_not_feasible",
            "family contract must explicitly set synthetic_feasible=true",
        )
    if (contract.get("generator_id"), contract.get("generator_version")) != (
        GENERATOR_ID, GENERATOR_VERSION,
    ):
        raise OfflineFallbackValidationError(
            "offline_fallback_generator_unsupported",
            f"family contract must select {GENERATOR_ID} {GENERATOR_VERSION}",
        )
    entity_count = _positive_int(
        contract.get("entity_count"), "offline_demo_data.entity_count",
    )
    if entity_count != _ENTITY_COUNT:
        raise OfflineFallbackValidationError(
            "offline_fallback_entity_contract",
            f"{SCHEMA_ID} v1 requires entity_count={_ENTITY_COUNT}",
        )
    fitting_prefix = _positive_int(
        contract.get("family_fitting_prefix_steps"),
        "offline_demo_data.family_fitting_prefix_steps",
    )
    if fitting_prefix != _FAMILY_FITTING_PREFIX_STEPS:
        raise OfflineFallbackValidationError(
            "offline_fallback_fitting_capacity_contract",
            f"{SCHEMA_ID} v1 requires family_fitting_prefix_steps="
            f"{_FAMILY_FITTING_PREFIX_STEPS}",
        )
    cadences = contract.get("supported_cadences")
    if not isinstance(cadences, list) or tuple(cadences) != SUPPORTED_CADENCES:
        raise OfflineFallbackValidationError(
            "offline_fallback_cadence_contract",
            f"supported_cadences must be {list(SUPPORTED_CADENCES)!r}",
        )
    horizon = _positive_int(
        contract.get("forecast_horizon_demo_value"),
        "offline_demo_data.forecast_horizon_demo_value",
    )
    tables = _object(contract.get("tables"), "offline_demo_data.tables")
    if set(tables) != {SERIES_FILENAME, OBSERVATIONS_FILENAME}:
        raise OfflineFallbackValidationError(
            "offline_fallback_table_schema",
            "tables must contain exactly series.csv and observations.csv",
        )
    normalized_tables = {
        SERIES_FILENAME: _table(
            tables[SERIES_FILENAME], f"tables.{SERIES_FILENAME}",
            SERIES_COLUMNS, ("series_id",),
        ),
        OBSERVATIONS_FILENAME: _table(
            tables[OBSERVATIONS_FILENAME], f"tables.{OBSERVATIONS_FILENAME}",
            OBSERVATION_COLUMNS, ("series_id", "timestamp"),
        ),
    }
    return {
        "schema_id": SCHEMA_ID,
        "synthetic_feasible": True,
        "generator_id": GENERATOR_ID,
        "generator_version": GENERATOR_VERSION,
        "entity_count": entity_count,
        "family_fitting_prefix_steps": fitting_prefix,
        "supported_cadences": list(SUPPORTED_CADENCES),
        "forecast_horizon_demo_value": horizon,
        "tables": normalized_tables,
    }


def _attempts(value: object) -> tuple[dict[str, object], ...]:
    if not isinstance(value, Sequence) or isinstance(value, (str, bytes)):
        raise OfflineFallbackValidationError(
            "offline_fallback_attempt_trail",
            "acquisition_attempts must be a list of typed records",
        )
    normalized: list[dict[str, object]] = []
    for index, raw in enumerate(value):
        root = f"acquisition_attempts[{index}]"
        item = _object(raw, root)
        _exact_keys(item, _ATTEMPT_KEYS, root)
        record: dict[str, object] = {}
        for key in ("status", "reason"):
            field = item.get(key)
            if not isinstance(field, str) or not field or field != field.strip():
                raise OfflineFallbackValidationError(
                    "offline_fallback_attempt_trail",
                    f"{root}.{key} must be a nonblank string",
                )
            record[key] = field
        for key in ("host", "cited_url"):
            field = item.get(key)
            if field is not None and (
                not isinstance(field, str) or not field
                or field != field.strip()
            ):
                raise OfflineFallbackValidationError(
                    "offline_fallback_attempt_trail",
                    f"{root}.{key} must be null or a nonblank string",
                )
            record[key] = field
        http_code = item.get("http_code")
        if http_code is not None and (
            isinstance(http_code, bool) or not isinstance(http_code, int)
            or not 100 <= http_code <= 599
        ):
            raise OfflineFallbackValidationError(
                "offline_fallback_attempt_trail",
                f"{root}.http_code must be null or 100..599",
            )
        record["http_code"] = http_code
        normalized.append(record)
    return tuple(normalized)


def _steps(value: Decimal, granularity: Decimal, root: str) -> int:
    result = value / granularity
    if result <= 0 or result != result.to_integral_value():
        raise OfflineFallbackValidationError(
            "offline_fallback_protocol_nonintegral",
            f"{root}={value} is not positive integral steps at "
            f"granularity={granularity}",
        )
    return int(result)


def _protocol(
    spec: object, contract: Mapping[str, object],
) -> tuple[tuple[_Quantity, ...], str, Decimal, int, dict[str, object]]:
    method_spec = _object(spec, "method_spec")
    comparison = _object(method_spec.get("comparison"), "method_spec.comparison")
    classification = _object(
        comparison.get("classification"), "comparison.classification",
    )
    family_id = classification.get("id")
    if family_id not in SUPPORTED_FAMILY_IDS:
        raise OfflineFallbackValidationError(
            "offline_fallback_family_unsupported",
            f"unsupported classification.id={family_id!r}",
        )
    data_requirements = _object(
        method_spec.get("data_requirements"), "method_spec.data_requirements",
    )
    if data_requirements.get("synthetic_feasible") is not True:
        raise OfflineFallbackValidationError(
            "offline_fallback_not_feasible",
            "method_spec.data_requirements.synthetic_feasible must be true",
        )
    protocol = _object(
        comparison.get("evaluation_protocol"), "comparison.evaluation_protocol",
    )
    scheme = _object(protocol.get("scheme"), "evaluation_protocol.scheme")
    if scheme.get("kind") != "single_holdout":
        raise OfflineFallbackValidationError(
            "offline_fallback_protocol_unsupported",
            "only typed single_holdout evaluation is supported",
        )
    if scheme.get("paper_value_status") != "paper_stated":
        raise OfflineFallbackValidationError(
            "offline_fallback_protocol_unsupported",
            "single_holdout scheme must be paper_stated",
        )
    scheme_ids = _ids(
        scheme.get("paper_element_ids"), "scheme.paper_element_ids",
    )
    raw_quantities = protocol.get("quantities")
    if not isinstance(raw_quantities, list):
        raise OfflineFallbackValidationError(
            "offline_fallback_protocol_roles",
            "evaluation_protocol.quantities must be a list",
        )
    by_role: dict[str, Mapping[str, object]] = {}
    for index, raw in enumerate(raw_quantities):
        item = _object(raw, f"evaluation_protocol.quantities[{index}]")
        role = item.get("role")
        if role not in PROTOCOL_ROLES or role in by_role:
            raise OfflineFallbackValidationError(
                "offline_fallback_protocol_roles",
                f"expected exactly one quantity per role {list(PROTOCOL_ROLES)!r}",
            )
        by_role[str(role)] = item
    if set(by_role) != set(PROTOCOL_ROLES):
        raise OfflineFallbackValidationError(
            "offline_fallback_protocol_roles",
            f"expected exactly one quantity per role {list(PROTOCOL_ROLES)!r}",
        )

    raw_units = [item.get("unit") for item in by_role.values()]
    if any(not isinstance(unit, str) for unit in raw_units):
        raise OfflineFallbackValidationError(
            "offline_fallback_protocol_cadence_disagreement",
            "every protocol unit must be a canonical string",
        )
    granularity_values = [
        _decimal(item.get("granularity"), f"{role}.granularity")
        for role, item in by_role.items()
    ]
    if len(set(raw_units)) != 1 or len(set(granularity_values)) != 1:
        raise OfflineFallbackValidationError(
            "offline_fallback_protocol_cadence_disagreement",
            "C, K, V, and T must use one identical unit and granularity",
        )
    unit = raw_units[0]
    if unit not in contract["supported_cadences"]:
        raise OfflineFallbackValidationError(
            "offline_fallback_cadence_unsupported",
            f"cadence {unit!r} is outside {contract['supported_cadences']!r}",
        )
    granularity = granularity_values[0]
    cadence_raw = _MICROSECONDS[str(unit)] * granularity
    if cadence_raw != cadence_raw.to_integral_value():
        raise OfflineFallbackValidationError(
            "offline_fallback_cadence_precision",
            "cadence is not exactly representable at microsecond precision",
        )
    cadence_microseconds = int(cadence_raw)

    normalized: list[_Quantity] = []
    demo_horizon = int(contract["forecast_horizon_demo_value"])
    for role in PROTOCOL_ROLES:
        item = by_role[role]
        root = f"evaluation_protocol.quantities[role={role}]"
        status = item.get("paper_value_status")
        raw_value = item.get("value")
        if role == "forecast_call_horizon" and status == "paper_unspecified":
            if raw_value is not None:
                raise OfflineFallbackValidationError(
                    "offline_fallback_horizon_authority",
                    f"{root}.value must be null when paper_unspecified",
                )
            role_steps = demo_horizon
            value_source = (
                "build_plan.offline_demo_data.forecast_horizon_demo_value"
            )
            normalized_raw = None
        elif status == "paper_stated":
            physical_value = _decimal(raw_value, f"{root}.value")
            role_steps = _steps(physical_value, granularity, f"{root}.value")
            value_source = "method_spec.comparison.evaluation_protocol"
            normalized_raw = raw_value
        else:
            raise OfflineFallbackValidationError(
                "offline_fallback_protocol_value_missing",
                "C, V, and T must be paper_stated; K must be paper_stated or "
                "paper_unspecified with a resolved family demo value",
            )
        normalized.append(_Quantity(
            role=role,
            raw_value=normalized_raw,
            unit=str(unit),
            granularity=granularity,
            paper_value_status=str(status),
            steps=role_steps,
            value_source=value_source,
            paper_element_ids=_ids(
                item.get("paper_element_ids"), f"{root}.paper_element_ids",
            ),
            axis_paper_element_ids=_ids(
                item.get("axis_paper_element_ids"),
                f"{root}.axis_paper_element_ids",
            ),
        ))
    scheme_provenance = {
        "kind": "single_holdout",
        "paper_value_status": "paper_stated",
        "paper_element_ids": list(scheme_ids),
    }
    return (
        tuple(normalized), str(unit), granularity, cadence_microseconds,
        scheme_provenance,
    )


def _plan(
    spec: object, build_plan: object, seed: object, acquisition_attempts: object,
) -> _Plan:
    contract = _family_contract(build_plan)
    if isinstance(seed, bool) or not isinstance(seed, int) \
            or not 0 <= seed <= 2**63 - 1:
        raise OfflineFallbackValidationError(
            "offline_fallback_seed", "seed must be an integer in 0..2^63-1",
        )
    quantities, unit, granularity, cadence, scheme = _protocol(spec, contract)
    roles = {item.role: item for item in quantities}
    context = roles["context_length"].steps
    horizon = roles["forecast_call_horizon"].steps
    validation = roles["validation_span"].steps
    test = roles["test_span"].steps
    if horizon > validation:
        raise OfflineFallbackValidationError(
            "offline_fallback_horizon_exceeds_validation",
            f"K={horizon} exceeds V={validation}",
        )
    if horizon > test:
        raise OfflineFallbackValidationError(
            "offline_fallback_horizon_exceeds_test",
            f"K={horizon} exceeds T={test}",
        )
    # R2C-065 owns static single-holdout axis capacity. Forecast-call K is a
    # separate per-call constraint and must not be folded into the dataset
    # extent or used to invent a fitting partition.
    fitting_prefix = int(contract["family_fitting_prefix_steps"])
    usable = fitting_prefix + context + validation + test
    entity_count = int(contract["entity_count"])
    if usable > _MAX_USABLE_STEPS \
            or usable * entity_count > _MAX_OBSERVATION_ROWS:
        raise OfflineFallbackValidationError(
            "offline_fallback_capacity_limit",
            f"full panel {entity_count}x{usable} exceeds the demo limit",
        )
    try:
        _ORIGIN + timedelta(
            microseconds=cadence * (usable - 1),
        )
    except OverflowError as exc:
        raise OfflineFallbackValidationError(
            "offline_fallback_timestamp_overflow",
            "protocol capacity and cadence exceed the timestamp range",
        ) from exc
    return _Plan(
        entity_count=entity_count,
        seed=seed,
        unit=unit,
        granularity=granularity,
        cadence_microseconds=cadence,
        quantities=quantities,
        family_fitting_prefix_steps=fitting_prefix,
        usable_steps=usable,
        attempts=_attempts(acquisition_attempts),
        scheme=scheme,
        family_contract=contract,
    )


def _entity_ids(count: int) -> tuple[str, ...]:
    return tuple(f"series_{index:03d}" for index in range(count))


def _decimal_text(value: Decimal) -> str:
    return format(value.quantize(Decimal("0.000000000001")), "f")


def _timestamp_text(value: datetime) -> str:
    timespec = "microseconds" if value.microsecond else "seconds"
    return value.isoformat(timespec=timespec).replace("+00:00", "Z")


def _timestamps(plan: _Plan) -> tuple[str, ...]:
    return tuple(
        _timestamp_text(
            _ORIGIN + timedelta(
                microseconds=plan.cadence_microseconds * step,
            )
        )
        for step in range(plan.usable_steps)
    )


def _jitter(seed: int, series_id: str, step: int) -> Decimal:
    identity = (
        f"{GENERATOR_VERSION}|{seed}|{series_id}|{step}".encode("utf-8")
    )
    bucket = int.from_bytes(hashlib.sha256(identity).digest()[:8], "big")
    unit_interval = Decimal(bucket) / Decimal(2**64 - 1)
    return (unit_interval * Decimal(2) - Decimal(1)) * Decimal("0.25")


def _series_payload(plan: _Plan) -> bytes:
    output = io.StringIO(newline="")
    writer = csv.writer(output, lineterminator="\n")
    writer.writerow([column["name"] for column in SERIES_COLUMNS])
    for index, series_id in enumerate(_entity_ids(plan.entity_count)):
        level = Decimal("20") + Decimal(index) * Decimal("1.5")
        amplitude = Decimal("3") + Decimal(index % 4) * Decimal("0.25")
        writer.writerow([
            series_id, _decimal_text(level), _decimal_text(amplitude),
        ])
    return output.getvalue().encode("utf-8")


def _observations_payload(plan: _Plan) -> bytes:
    output = io.StringIO(newline="")
    writer = csv.writer(output, lineterminator="\n")
    writer.writerow([column["name"] for column in OBSERVATION_COLUMNS])
    timestamps = _timestamps(plan)
    denominator = Decimal(plan.usable_steps - 1)
    for entity_index, series_id in enumerate(_entity_ids(plan.entity_count)):
        level = Decimal("20") + Decimal(entity_index) * Decimal("1.5")
        amplitude = Decimal("3") + Decimal(entity_index % 4) * Decimal("0.25")
        for step, timestamp in enumerate(timestamps):
            season_sin = _SIN[step % 12]
            season_cos = _COS[step % 12]
            time_fraction = Decimal(step) / denominator
            target = (
                level + amplitude * season_sin
                + Decimal("0.25") * amplitude * season_cos
                + Decimal("0.05") * Decimal(step)
                + _jitter(plan.seed, series_id, step)
            )
            writer.writerow([
                series_id,
                timestamp,
                _decimal_text(target),
                _decimal_text(season_sin),
                _decimal_text(season_cos),
                _decimal_text(time_fraction),
            ])
    return output.getvalue().encode("utf-8")


def _file_record(
    filename: str, payload: bytes, rows: int, table: Mapping[str, object],
    plan: _Plan,
) -> dict[str, object]:
    record: dict[str, object] = {
        "file": filename,
        "rows_kept": rows,
        "truncated": False,
        "sha256": hashlib.sha256(payload).hexdigest(),
        "bytes": len(payload),
        "columns": table["columns"],
        "primary_key": table["primary_key"],
        "entity_column": "series_id",
        "entities_kept": plan.entity_count,
        "entities_in_source": plan.entity_count,
        "entity_filter_applied": False,
    }
    if filename == OBSERVATIONS_FILENAME:
        timestamps = _timestamps(plan)
        record["time_axis"] = {
            "column": "timestamp",
            "steps_kept": plan.usable_steps,
            "steps_in_source": plan.usable_steps,
            "first_step": timestamps[0],
            "last_step": timestamps[-1],
            "rows_per_step_cap": None,
            "entity_column": "series_id",
            "entities_kept": plan.entity_count,
            "entities_in_source": plan.entity_count,
            "live_steps": plan.usable_steps,
            "last_live_step": timestamps[-1],
            "dead_tail_columns": [],
            "source_cadence": {
                "unit": plan.unit,
                "granularity": _json_number(plan.granularity),
            },
        }
    return record


def _mechanics() -> dict[str, object]:
    return {
        "panel_layout": "full_entity_by_timestamp_cartesian_panel",
        "row_order": ["series_id", "timestamp"],
        "entity_id_format": "series_{zero_based_index:03d}",
        "timestamp_origin": _timestamp_text(_ORIGIN),
        "season_period_steps": 12,
        "static_level_formula": "20 + 1.5 * entity_index",
        "static_amplitude_formula": "3 + 0.25 * (entity_index mod 4)",
        "season_covariates": "fixed 12-step decimal sine/cosine lookup",
        "time_fraction_formula": "step_index / (usable_steps - 1)",
        "target_formula": (
            "static_level + static_amplitude*season_sin + "
            "0.25*static_amplitude*season_cos + 0.05*step_index + jitter"
        ),
        "jitter": {
            "algorithm": "sha256",
            "input_utf8": (
                "{generator_version}|{seed}|{series_id}|{step_index}"
            ),
            "extract": "first_8_bytes_unsigned_big_endian",
            "mapping": "linear [0,2^64-1] to [-0.25,0.25]",
            "random_library_used": False,
        },
    }


