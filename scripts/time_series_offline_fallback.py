def _csv_rows(payload: bytes, filename: str) -> tuple[list[str], list[dict[str, str]]]:
    try:
        text = payload.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise OfflineFallbackValidationError(
            "offline_fallback_bundle_encoding", f"{filename} is not UTF-8",
        ) from exc
    reader = csv.DictReader(io.StringIO(text, newline=""))
    if reader.fieldnames is None:
        raise OfflineFallbackValidationError(
            "offline_fallback_bundle_header", f"{filename} has no header",
        )
    rows = list(reader)
    if any(None in row for row in rows):
        raise OfflineFallbackValidationError(
            "offline_fallback_bundle_rows", f"{filename} has over-wide rows",
        )
    return list(reader.fieldnames), rows


def _finite(value: str, root: str) -> float:
    try:
        result = float(value)
    except ValueError as exc:
        raise OfflineFallbackValidationError(
            "offline_fallback_bundle_dtype", f"{root} is not float64 text",
        ) from exc
    if not math.isfinite(result):
        raise OfflineFallbackValidationError(
            "offline_fallback_bundle_dtype", f"{root} must be finite",
        )
    return result


def _parse_timestamp(value: str, root: str) -> datetime:
    if not value.endswith("Z"):
        raise OfflineFallbackValidationError(
            "offline_fallback_bundle_timestamp",
            f"{root} must be ISO-8601 UTC ending in Z",
        )
    try:
        result = datetime.fromisoformat(value[:-1] + "+00:00")
    except ValueError as exc:
        raise OfflineFallbackValidationError(
            "offline_fallback_bundle_timestamp", f"{root} is not ISO-8601",
        ) from exc
    if result.tzinfo != timezone.utc:
        raise OfflineFallbackValidationError(
            "offline_fallback_bundle_timestamp", f"{root} is not UTC",
        )
    return result


def _validate_payloads(
    series_payload: bytes, observations_payload: bytes, plan: _Plan,
) -> None:
    series_header, series_rows = _csv_rows(series_payload, SERIES_FILENAME)
    expected_series_header = [item["name"] for item in SERIES_COLUMNS]
    if series_header != expected_series_header:
        raise OfflineFallbackValidationError(
            "offline_fallback_bundle_header",
            f"{SERIES_FILENAME} header must be {expected_series_header!r}",
        )
    expected_ids = list(_entity_ids(plan.entity_count))
    actual_ids = [row["series_id"] for row in series_rows]
    if actual_ids != expected_ids or len(actual_ids) != len(set(actual_ids)):
        raise OfflineFallbackValidationError(
            "offline_fallback_bundle_entity_ids",
            f"{SERIES_FILENAME} must carry the stable sorted entity ids",
        )
    for index, row in enumerate(series_rows):
        _finite(row["static_level"], f"series[{index}].static_level")
        amplitude = _finite(
            row["static_amplitude"], f"series[{index}].static_amplitude",
        )
        if amplitude <= 0:
            raise OfflineFallbackValidationError(
                "offline_fallback_bundle_dtype",
                f"series[{index}].static_amplitude must be positive",
            )

    obs_header, obs_rows = _csv_rows(
        observations_payload, OBSERVATIONS_FILENAME,
    )
    expected_obs_header = [item["name"] for item in OBSERVATION_COLUMNS]
    if obs_header != expected_obs_header:
        raise OfflineFallbackValidationError(
            "offline_fallback_bundle_header",
            f"{OBSERVATIONS_FILENAME} header must be {expected_obs_header!r}",
        )
    timestamps = list(_timestamps(plan))
    expected_keys = [
        (series_id, timestamp)
        for series_id in expected_ids
        for timestamp in timestamps
    ]
    actual_keys = [(row["series_id"], row["timestamp"]) for row in obs_rows]
    if actual_keys != expected_keys or len(actual_keys) != len(set(actual_keys)):
        raise OfflineFallbackValidationError(
            "offline_fallback_bundle_full_panel",
            "observations.csv must be the sorted full Cartesian panel of "
            "stable ids and regular timestamps",
        )
    parsed = [
        _parse_timestamp(value, f"timestamp[{index}]")
        for index, value in enumerate(timestamps)
    ]
    expected_delta = timedelta(microseconds=plan.cadence_microseconds)
    if any(
        right - left != expected_delta
        for left, right in zip(parsed, parsed[1:])
    ):
        raise OfflineFallbackValidationError(
            "offline_fallback_bundle_cadence",
            "observations.csv timestamps are not exactly regular",
        )
    for index, row in enumerate(obs_rows):
        for column in ("target", "season_sin", "season_cos", "time_fraction"):
            _finite(row[column], f"observations[{index}].{column}")


def _validate_manifest(
    manifest: object, series_payload: bytes, observations_payload: bytes,
    plan: _Plan,
) -> dict[str, object]:
    value = _object(manifest, PROVENANCE_FILENAME)
    normalized = json.loads(_canonical_json(dict(value)))
    recorded_digest = normalized.pop("bundle_digest", None)
    if not isinstance(recorded_digest, str) \
            or len(recorded_digest) != 64 \
            or recorded_digest != _digest(normalized):
        raise OfflineFallbackValidationError(
            "offline_fallback_bundle_digest",
            "PROVENANCE.json digest does not bind its canonical contents",
        )
    expected = _manifest(plan, series_payload, observations_payload)
    if dict(value) != expected:
        raise OfflineFallbackValidationError(
            "offline_fallback_provenance_disagreement",
            "PROVENANCE.json does not exactly describe the validated tables",
        )
    normalized["bundle_digest"] = recorded_digest
    return normalized


def _validate_stage(stage: Path, plan: _Plan) -> dict[str, object]:
    try:
        series_payload = (stage / SERIES_FILENAME).read_bytes()
        observations_payload = (stage / OBSERVATIONS_FILENAME).read_bytes()
        manifest = json.loads(
            (stage / PROVENANCE_FILENAME).read_text(encoding="utf-8")
        )
    except (OSError, json.JSONDecodeError) as exc:
        raise OfflineFallbackValidationError(
            "offline_fallback_staged_bundle",
            f"staged bundle is unreadable: {exc}",
        ) from exc
    _validate_payloads(series_payload, observations_payload, plan)
    return _validate_manifest(
        manifest, series_payload, observations_payload, plan,
    )


def _destination_conflicts(destination: Path) -> list[str]:
    return [
        filename for filename in PUBLISHED_FILENAMES
        if (destination / filename).exists()
    ]


def _file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _transaction_record(stage: Path) -> dict[str, object]:
    return {
        "schema_version": "1.0.0",
        "generator_id": GENERATOR_ID,
        "generator_version": GENERATOR_VERSION,
        "files": [
            {"file": filename, "sha256": _file_sha256(stage / filename)}
            for filename in PUBLISHED_FILENAMES
        ],
    }


def recover_interrupted_time_series_fallback(destination: Path) -> bool:
    """Remove only hash-matched files from an interrupted owned publication.

    The marker is installed before the first canonical rename. A later Stage
    2a invocation can therefore distinguish generator-owned partial files from
    researcher data. Any malformed marker or changed file refuses recovery and
    preserves every file.
    """
    destination = Path(destination)
    marker = destination / TRANSACTION_FILENAME
    if not marker.is_file():
        return False
    try:
        record = json.loads(marker.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise OfflineFallbackValidationError(
            "offline_fallback_transaction_marker",
            f"interrupted-publication marker is unreadable: {exc}",
        ) from exc
    expected_keys = {
        "schema_version", "generator_id", "generator_version", "files",
    }
    if (
        not isinstance(record, dict)
        or set(record) != expected_keys
        or record.get("schema_version") != "1.0.0"
        or record.get("generator_id") != GENERATOR_ID
        or record.get("generator_version") != GENERATOR_VERSION
        or not isinstance(record.get("files"), list)
    ):
        raise OfflineFallbackValidationError(
            "offline_fallback_transaction_marker",
            "interrupted-publication marker does not match the closed schema",
        )
    expected: dict[str, str] = {}
    for item in record["files"]:
        if (
            not isinstance(item, dict)
            or set(item) != {"file", "sha256"}
            or item.get("file") not in PUBLISHED_FILENAMES
            or not isinstance(item.get("sha256"), str)
            or len(item["sha256"]) != 64
        ):
            raise OfflineFallbackValidationError(
                "offline_fallback_transaction_marker",
                "interrupted-publication marker has an invalid file record",
            )
        expected[item["file"]] = item["sha256"]
    if set(expected) != set(PUBLISHED_FILENAMES):
        raise OfflineFallbackValidationError(
            "offline_fallback_transaction_marker",
            "interrupted-publication marker does not name the exact bundle",
        )
    for filename, digest in expected.items():
        target = destination / filename
        if target.exists() and (
            not target.is_file() or _file_sha256(target) != digest
        ):
            raise OfflineFallbackValidationError(
                "offline_fallback_transaction_conflict",
                f"refusing to remove changed interrupted file {filename!r}",
            )
    for filename in PUBLISHED_FILENAMES:
        (destination / filename).unlink(missing_ok=True)
    marker.unlink()
    return True


def _publish(stage: Path, destination: Path) -> None:
    if destination.exists() and not destination.is_dir():
        raise OfflineFallbackValidationError(
            "offline_fallback_destination",
            f"destination {destination} is not a directory",
        )
    conflicts = _destination_conflicts(destination)
    if conflicts:
        raise OfflineFallbackValidationError(
            "offline_fallback_destination_conflict",
            f"refusing to overwrite canonical files {conflicts!r}",
        )
    created = not destination.exists()
    destination.mkdir(parents=True, exist_ok=True)
    marker = destination / TRANSACTION_FILENAME
    marker_temp = stage / TRANSACTION_FILENAME
    published: list[Path] = []
    try:
        marker_temp.write_text(
            _canonical_json(_transaction_record(stage)) + "\n",
            encoding="utf-8",
        )
        os.replace(marker_temp, marker)
        # PROVENANCE.json is the completion marker and is moved last.
        for filename in PUBLISHED_FILENAMES:
            target = destination / filename
            if target.exists():
                raise FileExistsError(f"destination appeared during publish: {target}")
            source = stage / filename
            try:
                os.replace(source, target)
            except Exception:
                # A filesystem may report failure after completing the rename.
                # The vanished private source proves that this canonical file
                # belongs to this publication and must join rollback.
                if not source.exists() and target.exists():
                    published.append(target)
                raise
            else:
                published.append(target)
        marker.unlink()
    except Exception:
        for target in reversed(published):
            target.unlink(missing_ok=True)
        marker.unlink(missing_ok=True)
        marker_temp.unlink(missing_ok=True)
        if created:
            try:
                destination.rmdir()
            except OSError:
                pass
        raise


def generate_time_series_offline_fallback(
    spec: Mapping[str, object],
    build_plan: Mapping[str, object],
    destination: Path,
    *,
    seed: int,
    acquisition_attempts: Sequence[Mapping[str, object]],
    staging_parent: Path | None = None,
) -> OfflineFallbackOutcome:
    """Validate, stage, validate again, and publish the closed fallback.

    Unsupported or contradictory authority returns status=refused without
    publishing series.csv, observations.csv, or PROVENANCE.json.
    """
    try:
        plan = _plan(spec, build_plan, seed, acquisition_attempts)
        destination = Path(destination)
        if destination.exists() and not destination.is_dir():
            raise OfflineFallbackValidationError(
                "offline_fallback_destination",
                f"destination {destination} is not a directory",
            )
        recover_interrupted_time_series_fallback(destination)
        conflicts = _destination_conflicts(destination)
        if conflicts:
            raise OfflineFallbackValidationError(
                "offline_fallback_destination_conflict",
                f"refusing to overwrite canonical files {conflicts!r}",
            )
        series_payload = _series_payload(plan)
        observations_payload = _observations_payload(plan)
        _validate_payloads(series_payload, observations_payload, plan)
        manifest = _manifest(plan, series_payload, observations_payload)
        _validate_manifest(
            manifest, series_payload, observations_payload, plan,
        )
        destination.parent.mkdir(parents=True, exist_ok=True)
        stage_parent = (
            Path(staging_parent) if staging_parent is not None
            else destination.parent
        )
        stage_parent.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(
            prefix=".r2c-tsf-offline-", dir=stage_parent,
        ) as temporary:
            stage = Path(temporary)
            (stage / SERIES_FILENAME).write_bytes(series_payload)
            (stage / OBSERVATIONS_FILENAME).write_bytes(observations_payload)
            (stage / PROVENANCE_FILENAME).write_text(
                json.dumps(
                    manifest, indent=2, ensure_ascii=False, allow_nan=False,
                ) + "\n",
                encoding="utf-8",
            )
            normalized = _validate_stage(stage, plan)
            _publish(stage, destination)
        return OfflineFallbackOutcome(
            status="generated",
            code="offline_fallback_generated",
            reason=(
                f"generated {plan.entity_count} stable series x "
                f"{plan.usable_steps} regular {plan.unit} steps"
            ),
            provenance=normalized,
            written_files=PUBLISHED_FILENAMES,
        )
    except OfflineFallbackValidationError as exc:
        return OfflineFallbackOutcome(
            status="refused", code=exc.code, reason=str(exc),
        )
    except OSError as exc:
        return OfflineFallbackOutcome(
            status="refused",
            code="offline_fallback_write_failed",
            reason=f"offline fallback write failed without publication: {exc}",
        )


